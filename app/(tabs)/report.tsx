
import { useState, useEffect } from 'react';
import {
  View, Text, TouchableOpacity, StyleSheet,
  SafeAreaView, StatusBar, ActivityIndicator, ScrollView, Alert,
} from 'react-native';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { useRouter } from 'expo-router';
import { supabase } from '../../lib/supabase';
import Purchases, { LOG_LEVEL } from 'react-native-purchases';

const TEAL = '#0F6E56';
const RC_API_KEY = 'test_EqQiTqpCqhGmznRCRxVqzSukloA';

type SymptomLog = {
  id: string;
  symptom: string;
  severity: number;
  note: string;
  logged_at: string;
};

function formatDate(iso: string) {
  const d = new Date(iso);
  return d.toLocaleDateString('en-US', { weekday: 'short', month: 'short', day: 'numeric' });
}

function formatTime(iso: string) {
  const d = new Date(iso);
  return d.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });
}

function severityLabel(s: number) {
  if (s <= 3) return 'Mild';
  if (s <= 6) return 'Moderate';
  return 'Severe';
}

function severityColor(s: number) {
  if (s <= 3) return '#2E7D5E';
  if (s <= 6) return '#E08C00';
  return '#CC3333';
}

function buildHTML(logs: SymptomLog[], email: string, profile: any) {
  const today = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  const rows = logs.map(log => `
    <tr>
      <td>${log.symptom}</td>
      <td style="color:${severityColor(log.severity)};font-weight:600">${log.severity}/10 — ${severityLabel(log.severity)}</td>
      <td>${formatDate(log.logged_at)}</td>
      <td>${formatTime(log.logged_at)}</td>
      <td>${log.note || '—'}</td>
    </tr>
  `).join('');

  return `
    <html>
    <head>
      <style>
        body { font-family: -apple-system, Helvetica, sans-serif; padding: 40px; color: #222; }
        h1 { color: #0F6E56; font-size: 28px; margin-bottom: 4px; }
        .subtitle { color: #888; font-size: 14px; margin-bottom: 32px; }
        .meta { font-size: 13px; color: #555; margin-bottom: 8px; }
        table { width: 100%; border-collapse: collapse; margin-top: 24px; }
        th { background: #0F6E56; color: white; padding: 10px 12px; text-align: left; font-size: 13px; }
        td { padding: 10px 12px; border-bottom: 1px solid #EEE; font-size: 13px; }
        tr:nth-child(even) { background: #F9F9F9; }
        .footer { margin-top: 40px; font-size: 12px; color: #AAA; border-top: 1px solid #EEE; padding-top: 16px; }
        .summary { background: #F0FAF6; border-radius: 8px; padding: 16px 20px; margin-bottom: 24px; margin-top: 24px; }
        .summary-title { font-size: 13px; font-weight: 600; color: #0F6E56; margin-bottom: 8px; }
        .patient-card { background: #F9F9F9; border-radius: 8px; padding: 16px 20px; margin-bottom: 8px; }
      </style>
    </head>
    <body>
      <h1>vela</h1>
      <div class="subtitle">Symptom Report — Generated ${today}</div>
      <div class="patient-card">
        <div class="meta"><strong>Patient:</strong> ${profile?.full_name || email}</div>
        ${profile?.age ? `<div class="meta"><strong>Age:</strong> ${profile.age}</div>` : ''}
        ${profile?.gender ? `<div class="meta"><strong>Gender:</strong> ${profile.gender}</div>` : ''}
        ${profile?.weight_kg ? `<div class="meta"><strong>Weight:</strong> ${profile.weight_kg} kg</div>` : ''}
        ${profile?.height_cm ? `<div class="meta"><strong>Height:</strong> ${profile.height_cm} cm</div>` : ''}
        <div class="meta"><strong>Report period:</strong> ${formatDate(logs[logs.length - 1]?.logged_at)} – ${formatDate(logs[0]?.logged_at)}</div>
      </div>
      <div class="summary">
        <div class="summary-title">Summary</div>
        <div>${logs.length} total logs · Avg severity ${(logs.reduce((a, b) => a + b.severity, 0) / logs.length).toFixed(1)} · Peak ${Math.max(...logs.map(l => l.severity))}/10</div>
      </div>
      <table>
        <thead>
          <tr><th>Symptom</th><th>Severity</th><th>Date</th><th>Time</th><th>Note</th></tr>
        </thead>
        <tbody>${rows}</tbody>
      </table>
      <div class="footer">Generated by Vela · This report is intended to support medical consultations and does not constitute medical advice.</div>
    </body>
    </html>
  `;
}

export default function ReportScreen() {
  const router = useRouter();
  const [logs, setLogs] = useState<SymptomLog[]>([]);
  const [email, setEmail] = useState('');
  const [profile, setProfile] = useState<any>(null);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [isPro, setIsPro] = useState(false);
  const [purchasing, setPurchasing] = useState(false);

  useEffect(() => {
    setup();
  }, []);

  const setup = async () => {
    Purchases.setLogLevel(LOG_LEVEL.DEBUG);
    Purchases.configure({ apiKey: RC_API_KEY });

    try {
      const customerInfo = await Purchases.getCustomerInfo();
      setIsPro(customerInfo.entitlements.active['Vela Pro'] !== undefined);
    } catch (e) {
      console.log('RC error', e);
    }

    const { data: { session } } = await supabase.auth.getSession();
    if (!session) return;
    setEmail(session.user.email ?? '');

    const { data: profileData } = await supabase
      .from('profiles')
      .select('*')
      .eq('id', session.user.id)
      .single();

    if (profileData) setProfile(profileData);

    const { data } = await supabase
      .from('symptoms')
      .select('*')
      .eq('user_id', session.user.id)
      .order('logged_at', { ascending: false });

    if (data) setLogs(data);
    setLoading(false);
  };

  const handlePurchase = async () => {
    setPurchasing(true);
    try {
      const offerings = await Purchases.getOfferings();
      const current = offerings.current;
      if (!current) {
        Alert.alert('Not available', 'No offerings found. Please try again later.');
        setPurchasing(false);
        return;
      }
      const pkg = current.monthly;
      if (!pkg) {
        Alert.alert('Not available', 'Monthly plan not found.');
        setPurchasing(false);
        return;
      }
      const { customerInfo } = await Purchases.purchasePackage(pkg);
      setIsPro(customerInfo.entitlements.active['Vela Pro'] !== undefined);
    } catch (e: any) {
      if (!e.userCancelled) Alert.alert('Error', e.message);
    }
    setPurchasing(false);
  };

  const generatePDF = async () => {
    if (logs.length === 0) return;
    setGenerating(true);
    const html = buildHTML(logs, email, profile);
    const { uri } = await Print.printToFileAsync({ html });
    setGenerating(false);
    await Sharing.shareAsync(uri, { mimeType: 'application/pdf' });
  };

  return (
    <SafeAreaView style={styles.safe}>
      <StatusBar barStyle="dark-content" />
      <ScrollView contentContainerStyle={styles.container}>

        <TouchableOpacity onPress={() => router.back()} style={styles.back}>
          <Text style={styles.backText}>← Back</Text>
        </TouchableOpacity>

        <View style={styles.header}>
          <Text style={styles.appName}>vela</Text>
          <Text style={styles.subtitle}>Your doctor report</Text>
        </View>

        {loading && <ActivityIndicator color={TEAL} style={{ marginTop: 40 }} />}

        {!loading && logs.length === 0 && (
          <View style={styles.empty}>
            <Text style={styles.emptyText}>No logs yet.</Text>
            <Text style={styles.emptySubtext}>Log some symptoms first to generate a report.</Text>
          </View>
        )}

        {!loading && logs.length > 0 && (
          <>
            {profile?.full_name && (
              <View style={styles.profileCard}>
                <Text style={styles.profileName}>{profile.full_name}</Text>
                <Text style={styles.profileDetails}>
                  {[profile.age && `Age ${profile.age}`, profile.gender, profile.weight_kg && `${profile.weight_kg}kg`, profile.height_cm && `${profile.height_cm}cm`].filter(Boolean).join(' · ')}
                </Text>
              </View>
            )}

            <View style={styles.summaryCard}>
              <Text style={styles.summaryTitle}>Report summary</Text>
              <View style={styles.summaryRow}>
                <View style={styles.summaryItem}>
                  <Text style={styles.summaryNum}>{logs.length}</Text>
                  <Text style={styles.summaryLabel}>Total logs</Text>
                </View>
                <View style={styles.summaryItem}>
                  <Text style={styles.summaryNum}>
                    {(logs.reduce((a, b) => a + b.severity, 0) / logs.length).toFixed(1)}
                  </Text>
                  <Text style={styles.summaryLabel}>Avg severity</Text>
                </View>
                <View style={styles.summaryItem}>
                  <Text style={styles.summaryNum}>{Math.max(...logs.map(l => l.severity))}/10</Text>
                  <Text style={styles.summaryLabel}>Peak severity</Text>
                </View>
              </View>
            </View>

            {isPro ? (
              <TouchableOpacity style={styles.generateBtn} onPress={generatePDF} disabled={generating}>
                {generating
                  ? <ActivityIndicator color="#FFF" />
                  : <Text style={styles.generateBtnText}>Generate PDF report</Text>
                }
              </TouchableOpacity>
            ) : (
              <View style={styles.paywallCard}>
                <Text style={styles.paywallTitle}>Unlock PDF reports</Text>
                <Text style={styles.paywallDesc}>
                  Generate a doctor-ready PDF of your symptom history. Share it before any appointment.
                </Text>
                <View style={styles.paywallFeatures}>
                  <Text style={styles.paywallFeature}>✓ Unlimited PDF exports</Text>
                  <Text style={styles.paywallFeature}>✓ Full symptom history</Text>
                  <Text style={styles.paywallFeature}>✓ Formatted for doctors</Text>
                </View>
                <TouchableOpacity style={styles.generateBtn} onPress={handlePurchase} disabled={purchasing}>
                  {purchasing
                    ? <ActivityIndicator color="#FFF" />
                    : <Text style={styles.generateBtnText}>Unlock for $7 / month</Text>
                  }
                </TouchableOpacity>
              </View>
            )}

            <Text style={styles.hint}>
              {isPro
                ? 'Your report includes all logged symptoms, severity ratings, and timestamps.'
                : 'Free plan includes unlimited logging. Upgrade to export your report.'}
            </Text>
          </>
        )}

      </ScrollView>
    </SafeAreaView>
  );
}

